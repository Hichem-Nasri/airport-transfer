-- Step 3: exchange rates and flat-rate tariffs. All tariffs are stored in TND.

-- tnd_per_unit = how many TND for 1 unit of the currency (e.g. EUR 3.400000 = 1 EUR costs 3.4 TND).
-- Rows are never updated: a new rate is a new row, the latest one applies.
CREATE TABLE exchange_rates (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency_code VARCHAR(3)     NOT NULL REFERENCES currencies (code),
    tnd_per_unit  NUMERIC(14, 6) NOT NULL CHECK (tnd_per_unit > 0),
    is_demo       BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT chk_exchange_rates_not_base CHECK (currency_code <> 'TND')
);
CREATE INDEX idx_exchange_rates_latest ON exchange_rates (currency_code, created_at DESC, id DESC);
COMMENT ON COLUMN exchange_rates.is_demo IS 'TRUE = placeholder rate, NOT a real market rate.';

-- One flat price per (airport, destination zone, vehicle type).
CREATE TABLE tariffs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_id      BIGINT         NOT NULL REFERENCES airports (id),
    zone_id         BIGINT         NOT NULL REFERENCES zones (id),
    vehicle_type_id BIGINT         NOT NULL REFERENCES vehicle_types (id),
    price_tnd       NUMERIC(10, 3) NOT NULL CHECK (price_tnd > 0),
    active          BOOLEAN        NOT NULL DEFAULT TRUE,
    is_demo         BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_tariffs_route UNIQUE (airport_id, zone_id, vehicle_type_id)
);
CREATE INDEX idx_tariffs_zone ON tariffs (zone_id);
CREATE INDEX idx_tariffs_vehicle_type ON tariffs (vehicle_type_id);
COMMENT ON COLUMN tariffs.is_demo IS 'TRUE = placeholder price, NOT the real price grid. Replace before going live.';

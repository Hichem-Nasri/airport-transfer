-- Step 3: catalog data (zones, areas, airports, vehicle types, currencies).
-- V2 is reserved for the users table (step 2).

CREATE TABLE zones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20)  NOT NULL UNIQUE,
    name_fr       VARCHAR(100) NOT NULL,
    name_en       VARCHAR(100) NOT NULL,
    name_ar       VARCHAR(100) NOT NULL,
    display_order INT          NOT NULL DEFAULT 0,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

-- An area is a governorate (or a part of one, or a city): the place a customer picks.
-- Each area belongs to exactly one pricing zone; admins can move it to another zone.
CREATE TABLE areas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    VARCHAR(30)  NOT NULL UNIQUE,
    name_fr VARCHAR(100) NOT NULL,
    name_en VARCHAR(100) NOT NULL,
    name_ar VARCHAR(100) NOT NULL,
    zone_id BIGINT       NOT NULL REFERENCES zones (id),
    active  BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_areas_zone ON areas (zone_id);

CREATE TABLE airports (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code VARCHAR(3)    NOT NULL UNIQUE,
    name_fr   VARCHAR(150)  NOT NULL,
    name_en   VARCHAR(150)  NOT NULL,
    name_ar   VARCHAR(150)  NOT NULL,
    latitude  NUMERIC(9, 6),
    longitude NUMERIC(9, 6),
    active    BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE vehicle_types (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(20)  NOT NULL UNIQUE,
    name_fr        VARCHAR(100) NOT NULL,
    name_en        VARCHAR(100) NOT NULL,
    name_ar        VARCHAR(100) NOT NULL,
    min_passengers INT          NOT NULL CHECK (min_passengers >= 1),
    max_passengers INT          NOT NULL,
    display_order  INT          NOT NULL DEFAULT 0,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_vehicle_types_capacity CHECK (max_passengers >= min_passengers)
);

-- TND is the base currency of every tariff. `decimals` = number of decimals of the minor unit.
CREATE TABLE currencies (
    code     VARCHAR(3)  PRIMARY KEY,
    name     VARCHAR(60) NOT NULL,
    symbol   VARCHAR(8)  NOT NULL,
    decimals INT         NOT NULL CHECK (decimals BETWEEN 0 AND 3),
    active   BOOLEAN     NOT NULL DEFAULT TRUE
);
